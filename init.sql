-- =============================================
-- INITIALISATION BASE DE DONNÉES AURIANCE
-- Structure complète style Heidi
-- =============================================

-- Table des médecins
CREATE TABLE medecins (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR2(255) UNIQUE NOT NULL,
    password_hash VARCHAR2(255) NOT NULL,
    prenom VARCHAR2(100),
    nom VARCHAR2(100),
    specialite VARCHAR2(100),
    numero_rpps VARCHAR2(50) UNIQUE,
    cabinet_nom VARCHAR2(200),
    cabinet_adresse CLOB,
    telephone VARCHAR2(20),
    is_active NUMBER(1) DEFAULT 1,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Table des patients
CREATE TABLE patients (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    medecin_id NUMBER REFERENCES medecins(id) ON DELETE CASCADE,
    numero_dossier VARCHAR2(50) UNIQUE,
    prenom VARCHAR2(100) NOT NULL,
    nom VARCHAR2(100) NOT NULL,
    date_naissance DATE,
    genre VARCHAR2(10),
    numero_secu VARCHAR2(15),
    telephone VARCHAR2(20),
    email VARCHAR2(255),
    adresse CLOB,
    antecedents_medicaux CLOB,
    allergies CLOB,
    traitements_chroniques CLOB,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Table des consultations (CORE)
CREATE TABLE consultations (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    medecin_id NUMBER REFERENCES medecins(id) ON DELETE CASCADE,
    patient_id NUMBER REFERENCES patients(id) ON DELETE CASCADE,
    date_consultation TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    transcription_brute CLOB,
    transcription_structuree CLOB,
    resume_medical CLOB,
    duree_audio_seconds NUMBER,
    langue_detectee VARCHAR2(10),
    confiance_transcription FLOAT,
    codes_cim CLOB,
    codes_ccam CLOB,
    statut VARCHAR2(50) DEFAULT 'brouillon',
    tags CLOB,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Table des documents médicaux
CREATE TABLE documents_medicaux (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    consultation_id NUMBER REFERENCES consultations(id) ON DELETE CASCADE,
    type_document VARCHAR2(50) NOT NULL,
    modele_utilise VARCHAR2(100),
    contenu CLOB NOT NULL,
    variables CLOB,
    est_signe NUMBER(1) DEFAULT 0,
    date_signature TIMESTAMP,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Table des templates de documents
CREATE TABLE templates_documents (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    medecin_id NUMBER REFERENCES medecins(id) ON DELETE CASCADE,
    nom VARCHAR2(100) NOT NULL,
    type_document VARCHAR2(50) NOT NULL,
    specialite VARCHAR2(100),
    contenu_template CLOB NOT NULL,
    variables_disponibles CLOB,
    est_actif NUMBER(1) DEFAULT 1,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Table des codes médicaux
CREATE TABLE codes_medicaux (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code_cim VARCHAR2(20) NOT NULL,
    code_ccam VARCHAR2(20),
    libelle CLOB NOT NULL,
    chapitre VARCHAR2(100),
    est_actif NUMBER(1) DEFAULT 1,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Table des modèles IA
CREATE TABLE modeles_ia (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom VARCHAR2(100) NOT NULL,
    type_modele VARCHAR2(50),
    version VARCHAR2(50),
    est_actif NUMBER(1) DEFAULT 1,
    parametres CLOB,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Table des logs d'activité
CREATE TABLE logs_activite (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    medecin_id NUMBER REFERENCES medecins(id),
    action VARCHAR2(100) NOT NULL,
    entite_type VARCHAR2(50),
    entite_id NUMBER,
    details CLOB,
    ip_address VARCHAR2(45),
    user_agent CLOB,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Table des sessions utilisateurs
CREATE TABLE sessions (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    medecin_id NUMBER REFERENCES medecins(id),
    token VARCHAR2(500) UNIQUE NOT NULL,
    expires_at TIMESTAMP NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

